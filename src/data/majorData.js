function normalizeCode(code) {
  return String(code).replace(/^0+/, '') || '0'
}

function extractCode(className) {
  const match = String(className).match(/(\d+)/)
  return match ? normalizeCode(match[1]) : ''
}

// 旧判断函数（普通本科/研究生仍使用）
export function checkQualification(major) {
  if (!major) return { qualified: false, reason: '未找到该专业' }

  const level = major.level
  const className = String(major.className || '')
  const code = extractCode(className)

  if (level === '本科') {
    const name = major.name || ''
    if (benkeMajorNames.has(name)) {
      return { qualified: true, matchedName: name, level: '普通本科' }
    }
    return { qualified: false, reason: '该专业不在人工智能训练师报考条件范围内' }
  }

  if (level === '专科') {
    // 高职专科 + 高职本科：用名称匹配
    const name = major.name || ''
    if (gzMajorNames.has(name)) {
      return { qualified: true, matchedName: name, level: '高职专科' }
    }
    if (zyjyMajorNames.has(name)) {
      return { qualified: true, matchedName: name, level: '高职本科' }
    }
    return { qualified: false, reason: '该专业不在人工智能训练师报考条件范围内' }
  }

  if (level === '研究生') {
    // 研究生按一级学科名称匹配（className 中包含一级学科名即可）
    const matched = masterLevelOneNames.filter(n => className.includes(n) || (major.name || '').includes(n))
    if (matched.length > 0) {
      return { qualified: true, matchedName: matched[0], level: '研究生' }
    }
    return { qualified: false, reason: '该专业不在人工智能训练师报考条件范围内' }
  }

  return { qualified: false, reason: '不支持的学历层次' }
}

